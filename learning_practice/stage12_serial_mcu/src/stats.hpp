// ============================================================================
// stats.hpp - 统计数据结构
// 负责：收集和存储串口测试过程中的所有统计数据
// ============================================================================

#pragma once  // 头文件保护，防止重复包含

#include <cstdint>   // uint64_t、int64_t 等固定宽度整数类型
#include <climits>   // INT64_MAX 宏，int64_t 的最大值

// ============================================================================
// RxStats 结构体：接收统计信息
// ============================================================================

/**
 * @brief 接收统计信息结构体
 * 
 * 收集串口测试过程中的所有统计数据：
 *   - IMU 帧统计：总帧数、时间戳间隔
 *   - 能力帧统计：总帧数
 *   - 发送统计：成功/失败次数
 *   - 异常统计：时间戳异常、魔数异常
 *   - 连接统计：自动重连次数
 * 
 * 用于：
 *   1. 实时显示统计信息（每秒打印一次）
 *   2. 测试结束时生成验收报告
 *   3. 判断测试是否通过
 */
struct RxStats {
    // ========================================================================
    // 帧计数
    // ========================================================================
    
    /**
     * @brief IMU 帧总数
     * 
     * IMU 帧是下位机发送的惯性测量数据
     * 包含：roll/pitch/yaw 姿态角、角速度、时间戳
     * 正常频率：200Hz（约 5ms 一帧）
     * 
     * 如果 frames == 0，说明上行链路不通
     * 验收结论判定为 FAIL
     */
    uint64_t frames = 0;
    
    /**
     * @brief 能力帧总数
     * 
     * 能力帧包含三个开关状态：
     *   - following: 跟随模式（云台是否跟随目标）
     *   - power_rune: 能量机关（是否启用能量机关模式）
     *   - quanta: 量子开关（特殊功能开关）
     * 
     * 能力帧发送频率较低，只在状态变化时发送
     * 或者周期性发送（由下位机决定）
     */
    uint64_t caps_frames = 0;
    
    // ========================================================================
    // 异常计数
    // ========================================================================
    
    /**
     * @brief 异常总次数
     * 
     * 异常类型包括：
     *   1. 时间戳回退：dt <= 0（当前时间戳 <= 上一帧时间戳）
     *      - 可能原因：MCU 复位、时间戳溢出回绕
     *   2. 时间戳跳变过大：dt > 1000ms（帧间隔超过 1 秒）
     *      - 可能原因：丢帧、串口阻塞、下位机暂停发送
     *   3. 帧魔数错误：SOF != 0xA5 或 EOF != 0x5A
     *      - 可能原因：解析层被绕过、数据损坏
     * 
     * 异常次数用于验收判定：
     *   - anomalies == 0: PASS（完美）
     *   - anomalies <= 3: PASS（有少量异常，建议排查）
     *   - anomalies > 3: WARN（异常较多，需要排查）
     */
    uint64_t anomalies = 0;
    
    // ========================================================================
    // 发送统计（下行链路）
    // ========================================================================
    
    /**
     * @brief 发送成功次数
     * 
     * 调用 handle.send_sync() 返回 true 的次数
     * 表示指令成功写入串口缓冲区（不保证下位机已处理）
     */
    uint64_t tx_ok = 0;
    
    /**
     * @brief 发送失败次数
     * 
     * 调用 handle.send_sync() 返回 false 的次数
     * 可能原因：串口断开、超时、缓冲区满
     * 
     * 如果 tx_fail > 0 且开启了发送测试：
     *   验收结论从 PASS 降为 WARN
     */
    uint64_t tx_fail = 0;
    
    /**
     * @brief 自动重连成功次数
     * 
     * 当检测到串口断开时（is_connected() == false）
     * 程序会自动尝试重新连接
     * 
     * 每次成功重连，此计数器 +1
     * 
     * 如果 reconnects > 0：
     *   说明链路不稳定
     *   验收结论会标注有重连
     */
    uint64_t reconnects = 0;
    
    // ========================================================================
    // MCU 时间戳间隔统计
    // ========================================================================
    
    /**
     * @brief 最小帧间隔（毫秒）
     * 
     * 所有帧间隔中的最小值
     * 初始化为 INT64_MAX（64 位有符号整数最大值）
     * 
     * 正常值：约 5ms（200Hz 发送频率）
     * 如果下位机以 100Hz 发送，则约 10ms
     * 
     * 使用 INT64_MAX 作为初始值：
     *   第一帧时 dt_min_ms = INT64_MAX
     *   收到第二帧时，比较更新
     *   std::min(INT64_MAX, 5) = 5
     */
    int64_t dt_min_ms = INT64_MAX;
    
    /**
     * @brief 最大帧间隔（毫秒）
     * 
     * 所有帧间隔中的最大值
     * 初始化为 0
     * 
     * 正常值：约 5ms（200Hz 发送频率）
     * 
     * 如果 dt_max_ms 过大（如 > 1000ms）：
     *   说明存在丢帧或串口阻塞
     *   会被计入 anomalies 异常
     */
    int64_t dt_max_ms = 0;
    
    /**
     * @brief 帧间隔累加和（毫秒）
     * 
     * 所有帧间隔的累加和
     * 用于计算平均帧间隔
     * 
     * 平均间隔 = dt_sum_ms / (frames - 1)
     * 
     * 注意：frames - 1 是间隔数量
     * 如果有 100 帧，则有 99 个间隔
     */
    double dt_sum_ms = 0.0;
};

// ============================================================================
// 使用示例
// ============================================================================

/**
 * 在 serial_test.cpp 中的使用：
 * 
 * RxStats stats;  // 创建统计对象，所有成员初始化为 0
 * 
 * // 收到新帧时
 * ++stats.frames;
 * stats.dt_sum_ms += dt;
 * stats.dt_min_ms = std::min(stats.dt_min_ms, dt);
 * stats.dt_max_ms = std::max(stats.dt_max_ms, dt);
 * 
 * // 发现异常时
 * ++stats.anomalies;
 * 
 * // 发送指令时
 * if (ok) ++stats.tx_ok;
 * else ++stats.tx_fail;
 * 
 * // 重连成功时
 * ++stats.reconnects;
 * 
 * // 测试结束，打印报告
 * double avg_dt = stats.frames > 1 ? stats.dt_sum_ms / (stats.frames - 1) : 0.0;
 * print_report(opt, stats, duration_s, avg_fps, avg_dt);
 */